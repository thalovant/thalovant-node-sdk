// Regenerate resolved language rules using the pinned public Python reference.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
const temporary = mkdtempSync(join(tmpdir(), 'thalovant-listing-'));
try {
  // The reference generator validates package versions, Unicode and data overrides.
  // Use the package loader so regional files inherit their base language rules.
  execFileSync(process.argv[2] ?? 'python3', ['scripts/sync-reference-fixtures.py',
    '--data-dir', temporary, '--test-dir', 'test'], { stdio: 'inherit' });
  const data = JSON.parse(readFileSync(join(temporary, 'listing.json'), 'utf8'));
  writeFileSync('src/listing-data.ts', `// Generated by scripts/sync-listing-data.mjs from thalovant-languages v0.2.1.\n// Source: https://github.com/thalovant/thalovant-languages/tree/79ad5c1b8ff3d4427b2227ea72b978e85ebe2889\n// MIT; see LICENSE-languages. Do not edit language rules here.\nimport type { ListingData } from './listing.js';\nexport const listingData: ListingData = ${JSON.stringify(data, null, 2)};\n`);
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
