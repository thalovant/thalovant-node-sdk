// Regenerate from the canonical data checkout; never hand-edit the word lists.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { parse } from 'yaml';
const source = resolve(process.argv[2] ?? '../thalovant-languages');
const revision = '512f1993bed2fe20b2f874da35b1ba4d95be893b';
if (execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], {encoding:'utf8'}).trim() !== revision ||
    execFileSync('git', ['-C', source, 'status', '--porcelain'], {encoding:'utf8'}).trim()) {
  throw new Error('Use the clean thalovant-languages v0.1.1 checkout at '+revision);
}
const root = join(source, 'src/thalovant_languages/languages');
const keys = ['trailing_words','question_openers','question_words_anywhere','question_patterns','written_forms','slot_examples'];
const languages = Object.fromEntries(readdirSync(root, {withFileTypes:true}).filter(e=>e.isDirectory()).sort((a,b)=>a.name.localeCompare(b.name)).map(e=>{
  const data = parse(readFileSync(join(root,e.name,'language.yaml'),'utf8'));
  return [e.name,Object.fromEntries(keys.filter(key=>data[key]).map(key=>[key,data[key]]))];
}));
const scripts = parse(readFileSync(join(root,'scripts.yaml'),'utf8'));
const data = {sentence_ends:scripts.sentence_ends.spaced+scripts.sentence_ends.unspaced,languages};
writeFileSync('src/listing-data.ts', `// Generated by scripts/sync-listing-data.mjs from thalovant-languages v0.1.1.\n// Source: https://github.com/thalovant/thalovant-languages/tree/${revision}\n// MIT; see LICENSE-languages. Do not edit language rules here.\nimport type { ListingData } from './listing.js';\nexport const listingData: ListingData = ${JSON.stringify(data,null,2)};\n`);
writeFileSync('LICENSE-languages',readFileSync(join(source,'LICENSE')));
